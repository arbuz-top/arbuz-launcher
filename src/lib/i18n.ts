/** Приводит произвольное значение из конфига к известному языку. */
export function normLang(v: unknown): Lang {
  const known: string[] = ['en', 'pl', 'uk', 'eo', 'zh', 'et', 'fi', 'fr', 'de', 'be', 'sr', 'sk', 'ja', 'tg', 'uz', 'ky', 'lt', 'lv', 'iu', 'kk', 'olb', 'ka'];
  return typeof v === 'string' && known.includes(v) ? (v as Lang) : 'ru';
}

/** Язык из текущего состояния стора (вне React). */
export function langOf(): Lang {
  return normLang(useStore.getState().config.lang);
}

/** Короткое имя месяца для относительных дат. */
export function monthName(month: number, lang: Lang = langOf()): string {
  return (MONTHS[lang] ?? MONTHS.en ?? [])[month] ?? '';
}

function fill(s: string, vars?: Vars): string {
  if (!vars) return s;
  let out = s;
  for (const k of Object.keys(vars)) out = out.split('{' + k + '}').join(String(vars[k]));
  return out;
}

/** Перевод строки для конкретного языка; неизвестный ключ остаётся русским. */
export function translate(lang: Lang, key: string, vars?: Vars): string {
  const s =
    lang === 'ru'
      ? key
      : DICTS[lang][key] ?? (lang === 'olb' ? key : DICTS.en[key] ?? key);
  return fill(s, vars);
}

/** Перевод строки на текущий язык (вне React). */
export function t(key: string, vars?: Vars): string {
  return translate(langOf(), key, vars);
}

/** Склоняемая строка: tp('update', 3) → «3 обновления». */
export function tp(key: string, n: number, vars?: Vars): string {
  const lang = langOf();
  const forms = PLURALS[key]?.[lang] ?? PLURALS_AUTO[key]?.[lang] ?? PLURALS[key]?.en;
  if (!forms) return String(n);
  const f = pluralForm(lang, n);
  const s = f === 'one' ? forms[0] : f === 'few' ? forms[1] : forms[2];
  return fill(s, { n, ...(vars ?? {}) });
}

/** Какая форма склонения нужна для числа в этом языке. */
export function pluralForm(lang: Lang, n: number): 'one' | 'few' | 'many' {
  const n10 = Math.abs(n) % 10;
  const n100 = Math.abs(n) % 100;
  if (lang === 'ru' || lang === 'uk') {
    if (n10 === 1 && n100 !== 11) return 'one';
    if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return 'few';
    return 'many';
  }
  if (lang === 'pl') {
    if (n === 1) return 'one';
    if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return 'few';
    return 'many';
  }
  return n === 1 ? 'one' : 'many';
}

/** Хук переводчика: компонент перерисуется при смене языка. */
export function useT(): (key: string, vars?: Vars) => string {
  const lang = useStore((s) => s.config.lang);
  const l = normLang(lang);
  return useCallback((key: string, vars?: Vars) => translate(l, key, vars), [l]);
}

